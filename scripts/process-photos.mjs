/** Fraction of height to trim for screenshot-style sources: [top, bottom]. */
const CHROME_TRIM = {
  // (none currently — the old Facebook-chrome trim for cheeky-grin was
  // removed when the photo was replaced 2026-10-30)
}

async function processOne([file, slug]) {
  const src = join(SOURCE_DIR, file)
  await access(src)

  let pipeline = sharp(src).rotate() // honor EXIF orientation, then drop metadata
  const meta0 = await pipeline.metadata()
  if (CHROME_TRIM[slug] && meta0.height) {
    const [top, bottom] = CHROME_TRIM[slug]
    const y = Math.round(meta0.height * top)
    const h = Math.round(meta0.height * (1 - top - bottom))
    pipeline = pipeline.extract({ left: 0, top: y, width: meta0.width, height: h })
  }

  const fullDir = join(ROOT, 'public/photos/full')
  const thumbDir = join(ROOT, 'public/photos/thumb')
  await mkdir(fullDir, { recursive: true })
  await mkdir(thumbDir, { recursive: true })

  const fullPath = join(fullDir, `${slug}.webp`)
  const thumbPath = join(thumbDir, `${slug}.webp`)

  await pipeline.clone().resize({ width: 1600, withoutEnlargement: true }).webp({ quality: 80 }).toFile(fullPath)
  await pipeline.clone().resize({ width: 480, withoutEnlargement: true }).webp({ quality: 70 }).toFile(thumbPath)

  const meta = await sharp(fullPath).metadata()
  return { slug, file: `photos/full/${slug}.webp`, thumb: `photos/thumb/${slug}.webp`, width: meta.width ?? 0, height: meta.height ?? 0 }
}

const results = []
for (const p of PHOTOS) {
  const r = await processOne(p)
  results.push(r)
  console.log(`✓ ${r.slug}  ${r.width}×${r.height}`)
}

const ts = `// AUTO-GENERATED by scripts/process-photos.mjs — do not edit by hand.
// Captions live in src/data/birthday.ts keyed by slug.
export interface PhotoAsset {
  slug: string
  file: string
  thumb: string
  width: number
  height: number
}

export const PHOTO_ASSETS: PhotoAsset[] = ${JSON.stringify(results, null, 2)}
`
await writeFile(join(ROOT, 'src/data/photos.generated.ts'), ts)
console.log(`\nWrote src/data/photos.generated.ts with ${results.length} photos`)
